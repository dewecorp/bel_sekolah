    public static function init(): void
    {
        spl_autoload_register(function (string $class) {
            // Class di namespace Core -> core/
            if (strpos($class, 'Core\\') === 0) {
                $file = __DIR__ . '/' . str_replace('Core\\', '', $class) . '.php';
                if (file_exists($file)) {
                    require $file;
                }
                return;
            }

            // Class di namespace App\Models -> models/
            if (strpos($class, 'App\\Models\\') === 0) {
                $file = __DIR__ . '/../models/' . str_replace('App\\Models\\', '', $class) . '.php';
                if (file_exists($file)) {
                    require $file;
                }
                return;
            }

            // Class di namespace App\Controllers -> controllers/
            if (strpos($class, 'App\\Controllers\\') === 0) {
                $file = __DIR__ . '/../controllers/' . str_replace('App\\Controllers\\', '', $class) . '.php';
                if (file_exists($file)) {
                    require $file;
                }
                return;
            }
        });
    }

    public static function isInstalled(): bool
    {
        try {
            Database::getConnection();
            $tables = Database::fetchAll('SHOW TABLES LIKE "settings"');
            if (empty($tables)) {
                return false;
            }
            $row = Database::fetch('SELECT COUNT(*) as c FROM settings');
            return $row !== null && $row['c'] > 0;
        } catch (\Throwable $e) {
            return false;
        }
    }

    public static function settings(): array
    {
        if (self::$settingsCache !== null) {
            return self::$settingsCache;
        }

        $default = [
            'id'              => 1,
            'school_name'     => 'Sekolah Digital Indonesia',
            'school_logo'     => null,
            'school_address'  => '',
            'timezone'        => 'Asia/Jakarta',
            'time_format'     => '24',
            'default_volume'  => 0.8,
            'bell_duration'   => 5,
            'system_active'   => 1,
        ];

        try {
            $row = Database::fetch('SELECT * FROM settings WHERE id = 1');
            self::$settingsCache = $row ? array_merge($default, $row) : $default;
        } catch (\Throwable $e) {
            self::$settingsCache = $default;
        }

        return self::$settingsCache;
    }

    public static function invalidateSettingsCache(): void
    {
        self::$settingsCache = null;
    }

    public static function baseUrl(): string
    {
        $scheme = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
        $host = $_SERVER['HTTP_HOST'] ?? 'localhost';
        return $scheme . '://' . $host;
    }

    public static function url(string $path = ''): string
    {
        return self::baseUrl() . '/' . ltrim($path, '/');
    }

    public static function asset(string $path): string
    {
        return self::url(ltrim($path, '/'));
    }

    public static function logoUrl(): ?string
    {
        $logo = self::settings()['school_logo'] ?? null;
        if (empty($logo)) {
            return null;
        }
        return self::url($logo);
    }

    public static function storagePath(string $path = ''): string
    {
        return __DIR__ . '/../storage/' . ltrim($path, '/');
    }

    public static function now(string $timezone = 'Asia/Jakarta'): \DateTime
    {
        return new \DateTime('now', new \DateTimeZone($timezone));
    }

    public static function todayDate(string $timezone = 'Asia/Jakarta'): string
    {
        return self::now($timezone)->format('Y-m-d');
    }

    public static function todayTime(string $timezone = 'Asia/Jakarta'): string
    {
        return self::now($timezone)->format('H:i');
    }

    public static function dayName(string $timezone = 'Asia/Jakarta'): string
    {
        $days = ['Minggu', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];
        return $days[(int) self::now($timezone)->format('w')];
    }

    public static function csrfToken(): string
    {
        if (session_status() !== PHP_SESSION_ACTIVE) {
            session_start();
        }
        if (empty($_SESSION['csrf_token'])) {
            $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
        }
        return $_SESSION['csrf_token'];
    }

    public static function csrfField(): string
    {
        return '<input type="hidden" name="_csrf" value="' . self::csrfToken() . '">';
    }

    public static function verifyCsrf(): bool
    {
        if (session_status() !== PHP_SESSION_ACTIVE) {
            session_start();
        }
        $token = $_POST['_csrf'] ?? $_SERVER['HTTP_X_CSRF_TOKEN'] ?? '';
        return hash_equals($_SESSION['csrf_token'] ?? '', $token);
    }
